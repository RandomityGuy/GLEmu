const host = @import("host.zig");

const HMODULE = ?*anyopaque;

var loaded = false;

fn loadOne(comptime T: type, name: [*:0]const u8) ?T {
    const raw = host.resolve(name) orelse return null;
    return @ptrCast(raw);
}

